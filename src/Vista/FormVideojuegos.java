    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        // TODO add your handling code here:
        if(txtTitulo.getText().trim().isEmpty()){    //IF valida que el txtTitulo no esté vacio
            JOptionPane.showMessageDialog(null,"Debe ingresar un título para el videojuego"); 
            return;        }
                
        try{                                         //Trabajamos con TRY-CATCH
            Videojuegos vid = new Videojuegos();     //creamos el objeto            
            vid.setTitulo(txtTitulo.getText());      //y le asiganmos datos
            vid.setGenero(cbxGenero.getSelectedItem().toString());
            vid.setPrecio(Integer.parseInt(txtPrecio.getText()));
            
            lisVideojuegos.add(vid);                 //guardamos el objeto en el arreglo
            modTabla.addRow(vid.Registrar());        //mostramos el objeto en Jtable
            lblCantidad.setText(                     //mostrar la cantidad label
                "Videojuegos registradas: "+lisVideojuegos.size());
            JOptionPane.showMessageDialog(null,"Videojuego registrado correctamente");
            limpiarEntradas();        }
        catch(Exception ex){
            JOptionPane.showMessageDialog(null,"No se pudo registrar el videojuego"+ex);        }        
    }//GEN-LAST:event_btnRegistrarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
        int fila;
        fila=tblMostrar.getSelectedRow();           //obtener la fila seleccionada
        if(fila>=0){int res; res=JOptionPane.showConfirmDialog(null,"¿Desea eliminar el videojuego?","Eliminar",JOptionPane.YES_NO_OPTION);
            if(res==JOptionPane.YES_NO_OPTION){
            lisVideojuegos.remove(fila);            //elimina el objeto de Arreglo
            modTabla.removeRow(fila);               //elimina fila JTable
            lblCantidad.setText("Videojuego registrado"+lisVideojuegos.size());      //actualiza el label
        }
        JOptionPane.showMessageDialog(null,"Videojuego eliminado correctamente"); 
        }else {
            JOptionPane.showMessageDialog(null,"Seleccione un videojuego de la tabla");}
    }//GEN-LAST:event_btnEliminarActionPerformed

